## Project-original content

The synthetic SOP corpus (\`data/synthetic/sops/\`, 30 documents plus one
superseded version), the adversarial fixtures (\`data/synthetic/adversarial/\`),
and the labelled evaluation datasets (\`data/eval/notes_train.jsonl\`,
\`notes_test.jsonl\`, \`retrieval_questions.jsonl\`) are **original to this
project**. They were authored for it, contain no copied third-party text, and
describe no real factory, customer, worker or product. They are synthetic
demonstration data and must never be presented as real factory data
(\`docs/evaluation/synthetic-data.md\`, \`data/synthetic/README.md\`,
\`data/eval/README.md\`).

The repository's own source code is covered by the licence named in
\`README.md\`.
EOF
} > "$out"

echo "gen_licenses: wrote $out"
